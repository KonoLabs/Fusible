//! Step 1 — command-line definition.
//!
//! `clap` is isolated in its own module so `main.rs` only talks to one
//! domain type (`Cli`) and stays readable: the Read → Parse → Lint →
//! Diagnostics pipeline already takes all the attention it needs.

use std::path::PathBuf;

use clap::builder::ValueHint;
use clap::Parser;

/// Fusible — electronic linter: a fuse that blows to block firmware generation.
#[derive(Debug, Parser)]
#[command(
    name = "fusible",
    version,
    about = "Electronic linter: the fuse blows to block firmware code generation",
    long_about = None,
    arg_required_else_help = true,
    after_help = "Example: fusible --input examples/circuit.json --mcu stm32g431"
)]
pub struct Cli {
    /// Path to the Circuit JSON file (generated by tscircuit)
    #[arg(short = 'i', long, value_name = "FILE", value_hint = ValueHint::FilePath)]
    pub input: PathBuf,

    /// Silicon target, e.g. `stm32g431` (consumed by pin-muxing in phase 2)
    #[arg(long, value_name = "MCU")]
    pub mcu: Option<String>,
}
